export const dictionaries = { en, ru, uk };
const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: TKey) => string }>({
  lang: "en",
  setLang: () => {},
  t: (k) => en[k],
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>("en");
  useEffect(() => {
    let saved: string | null = null;
    try { saved = localStorage.getItem("nsb.lang"); } catch { /* storage unavailable */ }
    setLang(initialLanguage(saved, navigator.language));
  }, []);
  useEffect(() => { document.documentElement.lang = lang; }, [lang]);
  const chooseLanguage = (next: Lang) => {
    setLang(next);
    try { localStorage.setItem("nsb.lang", next); } catch { /* storage unavailable */ }
  };
  const d = dictionaries[lang];
  return <Ctx.Provider value={{ lang, setLang: chooseLanguage, t: (k) => d[k] }}>{children}</Ctx.Provider>;
}
export const useT = () => useContext(Ctx);

export function stepLabel(t: (k: TKey) => string, name: string) {
  const k = `step_${name}` as TKey;
  return k in en ? t(k) : name;
}

export function fill(s: string, vars: Record<string, string | number>) {
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

export function formatArrival(time: AttestationTime | undefined, lang: Lang, t: (k: TKey) => string): string {
  if (!time) return t("timingUnknown");
  const locale = languageLocale(lang);
  const number = new Intl.NumberFormat(locale);
  const quantity = time.max ?? time.min;
  const plural = new Intl.PluralRules(locale).select(quantity);
  const key = `${time.unit}_${["one", "few", "many"].includes(plural) ? plural : "other"}` as TKey;
  return `~${number.format(time.min)}${time.max ? `–${number.format(time.max)}` : ""} ${t(key)}`;
}
